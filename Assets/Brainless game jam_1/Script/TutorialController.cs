using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

// FULL REPLACEMENT of the old TutorialController (same class name, so the line
//   if (TutorialController.IsOpen) return;   in PathSelectInput keeps working).
// Put it on the "RoundManager" object.
//
// An INTERACTIVE tutorial that runs in the real scene:
//   1. CAVES    : arrows on the 3 caves ("monsters come from here")             [game frozen, press NEXT]
//   2. PICK     : arrows + glowing lines on the 3 paths, player must click one   [live]
//   3. SWITCH   : player must pick a DIFFERENT path                              [live]
//   4. HALT     : arrow follows a gnome, player must click it, then click again  [live]
//   5. READY    : "good luck", press PLAY                                        [frozen]
// When it ends (PLAY or SKIP) the scene reloads so the real round starts fresh (tutorial gnomes don't count).
public class TutorialController : MonoBehaviour
{
    // true while the tutorial wants the game frozen: PathSelectInput ignores input then
    public static bool IsOpen { get; private set; }
    static bool seenThisSession;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    static void ResetStatics() { IsOpen = false; seenThisSession = false; }

    enum Step { Caves, PickPath, Switch, Halt, Ready }

    [Header("Scene")]
    [SerializeField] GnomeSpawner spawner;

    [Header("UI (a small banner, not a full screen panel)")]
    [SerializeField] GameObject banner;
    [SerializeField] TMP_Text messageText;
    [SerializeField] Button nextButton;
    [SerializeField] TMP_Text nextButtonLabel;     // optional: text on the button (NEXT / PLAY)
    [SerializeField] Button skipButton;

    [Header("Messages (edit freely)")]
    [TextArea(2, 4)][SerializeField] string cavesMsg = "Monsters come out of these 3 caves. A flame shows up first as a warning!";
    [TextArea(2, 4)][SerializeField] string pickMsg = "These are your 3 paths. Click any path (or press 1, 2, 3) to send your gnomes down it.";
    [TextArea(2, 4)][SerializeField] string switchMsg = "You can switch any time. Click a different path to send the next gnomes there.";
    [TextArea(2, 4)][SerializeField] string haltMsg = "Click a gnome to make it wait.";
    [TextArea(2, 4)][SerializeField] string releaseMsg = "Click it again to let it go. A waiting gnome blocks the ones behind it!";
    [TextArea(2, 4)][SerializeField] string readyMsg = "Save as many gnomes as you can before the timer runs out. Good luck!";

    [Header("Arrows")]
    [SerializeField] Sprite customArrowSprite;     // optional: your own arrow art (drawn pointing DOWN). Empty = generated by code
    [SerializeField] Color arrowColor = new Color(1f, 0.9f, 0.2f);
    [SerializeField] float arrowScale = 1f;
    [SerializeField] float minTravelBeforePointing = 2.5f;   // don't point at a gnome still hidden behind the tree

    Step step;
    int startRoute;
    bool sawHalt;
    GnomeWalker haltTarget;
    Camera cam;

    readonly List<SpriteRenderer> arrows = new List<SpriteRenderer>();
    readonly List<LineRenderer> lines = new List<LineRenderer>();
    Material overlayMat;

    // ---------------------------------------------------------------- setup

    void Start()
    {
        cam = Camera.main;
        if (spawner == null || banner == null)
        {
            Debug.LogError("TutorialController: assign Spawner and Banner.");
            enabled = false;
            return;
        }

        if (nextButton != null) nextButton.onClick.AddListener(OnNext);
        if (skipButton != null) skipButton.onClick.AddListener(Finish);

        if (seenThisSession) { banner.SetActive(false); enabled = false; return; }

        overlayMat = MakeMaterial();
        BuildArrows();
        BuildLines();
        GoTo(Step.Caves);
    }

    static Material MakeMaterial()
    {
        Shader sh = Shader.Find("Universal Render Pipeline/2D/Sprite-Unlit-Default");
        if (sh == null) sh = Shader.Find("Sprites/Default");
        return new Material(sh);
    }

    void BuildArrows()
    {
        Sprite sprite = customArrowSprite != null ? customArrowSprite : MakeArrowSprite();
        int count = Mathf.Max(3, spawner.Routes.Length);
        for (int i = 0; i < count; i++)
        {
            var go = new GameObject("TutorialArrow" + i);
            go.transform.SetParent(transform, false);
            go.transform.localScale = Vector3.one * arrowScale;
            var sr = go.AddComponent<SpriteRenderer>();
            sr.sprite = sprite;
            sr.sharedMaterial = overlayMat;
            sr.color = arrowColor;
            sr.sortingOrder = 20000;               // above the foreground tree (10000)
            go.SetActive(false);
            arrows.Add(sr);
        }
    }

    void BuildLines()
    {
        foreach (var route in spawner.Routes)
        {
            var go = new GameObject("TutorialPathLine");
            go.transform.SetParent(transform, false);
            var lr = go.AddComponent<LineRenderer>();
            lr.useWorldSpace = true;
            lr.sharedMaterial = overlayMat;
            lr.widthMultiplier = 0.14f;
            lr.numCapVertices = 4;
            lr.numCornerVertices = 4;
            lr.sortingOrder = 19000;
            lr.positionCount = route.Count;
            for (int i = 0; i < route.Count; i++)
            {
                Vector3 p = route.GetPoint(i);
                lr.SetPosition(i, new Vector3(p.x, p.y, 0f));
            }
            go.SetActive(false);
            lines.Add(lr);
        }
    }

    // A simple down-pointing arrow with a dark outline, generated in code (no art needed).
    static Sprite MakeArrowSprite()
    {
        const int N = 64;
        bool[,] fill = new bool[N, N];
        for (int y = 0; y < N; y++)
            for (int x = 0; x < N; x++)
                fill[x, y] = InArrow(x + 0.5f, y + 0.5f);

        var px = new Color32[N * N];
        for (int y = 0; y < N; y++)
        {
            for (int x = 0; x < N; x++)
            {
                Color32 c = new Color32(0, 0, 0, 0);
                if (fill[x, y]) c = new Color32(255, 255, 255, 255);
                else
                {
                    bool near = false;
                    for (int dy = -3; dy <= 3 && !near; dy++)
                        for (int dx = -3; dx <= 3; dx++)
                        {
                            int nx = x + dx, ny = y + dy;
                            if (nx < 0 || ny < 0 || nx >= N || ny >= N) continue;
                            if (dx * dx + dy * dy <= 9 && fill[nx, ny]) { near = true; break; }
                        }
                    if (near) c = new Color32(30, 20, 0, 255);
                }
                px[y * N + x] = c;
            }
        }

        var tex = new Texture2D(N, N, TextureFormat.RGBA32, false);
        tex.filterMode = FilterMode.Bilinear;
        tex.wrapMode = TextureWrapMode.Clamp;
        tex.SetPixels32(px);
        tex.Apply();
        return Sprite.Create(tex, new Rect(0, 0, N, N), new Vector2(0.5f, 0.5f), 64f);
    }

    static bool InArrow(float x, float y)   // texture y = 0 is the bottom, so the tip is at the bottom
    {
        if (y >= 6f && y <= 34f) return Mathf.Abs(x - 32f) <= (y - 6f) / 28f * 22f;   // head
        if (y > 34f && y <= 58f) return Mathf.Abs(x - 32f) <= 8f;                       // shaft
        return false;
    }

    // ---------------------------------------------------------------- flow

    void GoTo(Step s)
    {
        step = s;
        Debug.Log("Tutorial step: " + s);
        sawHalt = false;
        haltTarget = null;
        banner.SetActive(true);

        bool frozen = (s == Step.Caves || s == Step.Ready);
        IsOpen = frozen;
        Time.timeScale = frozen ? 0f : 1f;

        if (nextButton != null) nextButton.gameObject.SetActive(frozen);
        if (nextButtonLabel != null) nextButtonLabel.text = s == Step.Ready ? "PLAY" : "NEXT";

        switch (s)
        {
            case Step.Caves: SetMessage(cavesMsg); break;
            case Step.PickPath: SetMessage(pickMsg); break;
            case Step.Switch: SetMessage(switchMsg); startRoute = spawner.SelectedRoute; break;
            case Step.Halt: SetMessage(haltMsg); break;
            case Step.Ready: SetMessage(readyMsg); break;
        }
    }

    void SetMessage(string m) { if (messageText != null) messageText.text = m; }

    void OnNext()
    {
        if (step == Step.Caves) GoTo(Step.PickPath);
        else if (step == Step.Ready) Finish();
    }

    void Update()
    {
        // the round ended while the tutorial was running (e.g. the player dawdled): just start the real game
        if (RoundManager.Instance != null && !RoundManager.Instance.IsPlaying) { Finish(); return; }

        if (Input.GetKeyDown(KeyCode.Return) || Input.GetKeyDown(KeyCode.KeypadEnter))
            OnNext();

        switch (step)
        {
            case Step.Caves:
                ArrowsAtCaves();
                SetLines(false);
                break;

            case Step.PickPath:
                ArrowsAtPaths();
                SetLines(true);
                if (spawner.SelectedRoute >= 0) GoTo(Step.Switch);
                break;

            case Step.Switch:
                ArrowsAtPaths();
                SetLines(true);
                if (spawner.SelectedRoute >= 0 && spawner.SelectedRoute != startRoute) GoTo(Step.Halt);
                break;

            case Step.Halt:
                SetLines(false);
                HaltStep();
                break;

            case Step.Ready:
                HideArrowsFrom(0);
                SetLines(false);
                break;
        }
    }

    void HaltStep()
    {
        // keep gnomes coming so there is something to click
        if (GnomeWalker.All.Count == 0 && spawner.SelectedRoute < 0) spawner.SelectRoute(0);

        if (!sawHalt)
        {
            if (haltTarget == null) haltTarget = PickTargetGnome();

            foreach (var g in GnomeWalker.All)
                if (g != null && g.Halted) { sawHalt = true; haltTarget = g; SetMessage(releaseMsg); break; }
        }
        else if (haltTarget == null)          // the halted gnome is gone (caught): move on
        {
            GoTo(Step.Ready);
            return;
        }
        else if (!haltTarget.Halted)          // released
        {
            GoTo(Step.Ready);
            return;
        }

        if (haltTarget != null) { ArrowAt(0, haltTarget.transform.position, 1.6f); HideArrowsFrom(1); }
        else HideArrowsFrom(0);
    }

    // a gnome that has walked out from behind the tree, preferring the one that has walked the least
    GnomeWalker PickTargetGnome()
    {
        GnomeWalker best = null;
        float bestT = float.MaxValue;
        foreach (var g in GnomeWalker.All)
        {
            if (g == null || g.Halted || g.Traveled < minTravelBeforePointing) continue;
            if (g.Traveled < bestT) { bestT = g.Traveled; best = g; }
        }
        return best;
    }

    void Finish()
    {
        seenThisSession = true;
        IsOpen = false;
        Time.timeScale = 1f;
        if (banner != null) banner.SetActive(false);
        if (RoundManager.Instance != null) RoundManager.Instance.Restart();   // fresh round, tutorial gnomes don't count
    }

    void OnDestroy()
    {
        if (IsOpen) { IsOpen = false; Time.timeScale = 1f; }
    }

    // ---------------------------------------------------------------- arrows & lines

    void ArrowsAtCaves()
    {
        var routes = spawner.Routes;
        for (int i = 0; i < routes.Length && i < arrows.Count; i++)
        {
            var r = routes[i];
            Vector3 p = r.Monster != null ? r.Monster.transform.position : r.GetPoint(r.Count - 1);
            ArrowAt(i, p, 1.0f);
        }
        HideArrowsFrom(routes.Length);
    }

    void ArrowsAtPaths()
    {
        var routes = spawner.Routes;
        for (int i = 0; i < routes.Length && i < arrows.Count; i++)
            ArrowAt(i, routes[i].GetPoint(routes[i].Count / 2), 1.0f);
        HideArrowsFrom(routes.Length);
    }

    // Arrow floats above the target pointing down; targets near the top of the screen get it below, pointing up.
    void ArrowAt(int index, Vector3 target, float lift)
    {
        var a = arrows[index];
        a.gameObject.SetActive(true);

        bool below = cam.WorldToViewportPoint(target).y > 0.72f;
        float dist = lift + Mathf.Sin(Time.unscaledTime * 6f) * 0.15f;
        a.transform.position = new Vector3(target.x, target.y + (below ? -dist : dist), 0f);
        a.transform.rotation = Quaternion.Euler(0f, 0f, below ? 180f : 0f);
    }

    void HideArrowsFrom(int start)
    {
        for (int i = start; i < arrows.Count; i++) arrows[i].gameObject.SetActive(false);
    }

    void SetLines(bool on)
    {
        float pulse = 0.55f + 0.35f * Mathf.Sin(Time.unscaledTime * 4f);
        for (int i = 0; i < lines.Count; i++)
        {
            lines[i].gameObject.SetActive(on);
            if (!on) continue;
            Color c = (i == spawner.SelectedRoute) ? Color.white : arrowColor;   // the chosen path shows white
            c.a = pulse;
            lines[i].startColor = c;
            lines[i].endColor = c;
        }
    }
}